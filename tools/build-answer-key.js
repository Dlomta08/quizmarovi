#!/usr/bin/env node
/*
 * Builds supabase/answer-key.sql: the correct answer of every live math problem, for the private
 * `problem_keys` table. The database uses it to decide whether an answer is right (so XP can't be
 * faked from the browser), to pick the daily problem, and to pick and grade duel problems
 * (area / topic groups / difficulty are the duel filters).
 *
 *   node tools/build-answer-key.js
 *
 * (tools/build-quiz-index.js runs this automatically.)
 * Then paste supabase/answer-key.sql into Supabase -> SQL Editor -> Run.
 * Re-run (both steps) whenever quizzes are added or answers/tags change. Only quizzes listed in
 * quizzes.json are included, same as on the site.
 * Needs the area/topic_groups/difficulty columns added by supabase/duels.sql.
 */
"use strict";
const fs = require("fs");
const path = require("path");
const { ROOT, loadTags, listMathQuizzes } = require("./tags-lib");

const sqlText = s => (s == null ? "null" : "'" + String(s).replace(/'/g, "''") + "'");
const sqlArray = list => "'{" + list.map(x => String(x).replace(/[{},"'\\\s]/g, "")).join(",") + "}'";

function build() {
  const live = JSON.parse(fs.readFileSync(path.join(ROOT, "quizzes.json"), "utf8")).math || {};
  const isLive = (g, y, q) => ((live[g] || {})[y] || []).includes(q);

  // leaf topic -> its top-level group (the duel topic filter)
  const tags = loadTags();
  const groupOf = t => {
    const info = tags.topics.get(t);
    return info ? (info.parent || info.id) : null;
  };

  const rows = [];
  for (const quiz of listMathQuizzes()) {
    if (!isLive(quiz.grade, quiz.year, quiz.quiz)) continue;
    quiz.problems.forEach((p, i) => {
      const id = `${quiz.grade}-${quiz.year}-${quiz.quiz}-${i + 1}`;   // same id as progress.js / attempts
      const hasOptions = Array.isArray(p.options) && p.options.length > 0;
      const correct = (Array.isArray(p.correct) ? p.correct : [p.correct])
        .filter(c => Number.isInteger(c) && c >= 0 && hasOptions && c < p.options.length);
      const groups = [...new Set((p.topics || []).map(groupOf).filter(Boolean))];
      const difficulty = Number.isInteger(p.difficulty) ? p.difficulty : "null";
      rows.push(`('${id}',${quiz.grade},${sqlArray(correct)},${hasOptions && correct.length > 0},` +
                `${sqlText(p.area || null)},${sqlArray(groups)},${difficulty})`);
    });
  }

  const sql = `-- GENERATED by tools/build-answer-key.js — do not edit by hand.
-- Correct answers of ${rows.length} live math problems. Run in Supabase -> SQL Editor
-- (after 02-daily-problem.sql and duels.sql).
-- Safe to re-run: it replaces the whole table in one transaction.
begin;
delete from public.problem_keys;
insert into public.problem_keys (problem_id, grade, correct, has_options, area, topic_groups, difficulty) values
${rows.join(",\n")};
commit;
`;
  const out = path.join(ROOT, "supabase", "answer-key.sql");
  fs.writeFileSync(out, sql);
  const graded = rows.filter(r => /,true,/.test(r)).length;
  return { file: path.relative(ROOT, out), count: rows.length, graded };
}

if (require.main === module) {
  const { file, count, graded } = build();
  console.log(`wrote ${file}: ${count} problems (${graded} with a checkable answer)`);
}
module.exports = { build };
